def main():
    if len(sys.argv) != 3:
        raise SystemExit("Usage: build_es_co_po.py <odoo-export.po> <output.po>")
    catalog = polib.pofile(sys.argv[1], encoding="utf-8")
    catalog.metadata["Language"] = "es_CO"
    catalog.metadata["Content-Type"] = "text/plain; charset=UTF-8"
    missing = sorted({entry.msgid for entry in catalog if entry.msgid and entry.msgid not in TRANSLATIONS})
    if missing:
        print("Unmapped terms:")
        print("\n".join(repr(term) for term in missing))
        raise SystemExit(f"Refusing incomplete catalog: {len(missing)} terms")
    for entry in catalog:
        if entry.msgid in TRANSLATIONS:
            entry.msgstr = TRANSLATIONS[entry.msgid]
            if "fuzzy" in entry.flags:
                entry.flags.remove("fuzzy")
    output = Path(sys.argv[2])
    output.parent.mkdir(parents=True, exist_ok=True)
    catalog.save(str(output))
    print(f"Wrote {len(catalog)} entries; translated {sum(bool(entry.msgstr) for entry in catalog)}.")


if __name__ == "__main__":
    main()
